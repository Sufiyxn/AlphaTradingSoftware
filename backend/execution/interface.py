from typing import Protocol, Sequence

from backend.portfolio.models import Position

from .capabilities import PlatformCapabilities
from .models import AccountSnapshot, Order, OrderRequest, Quote


class TradingPlatformAdapter(Protocol):
    """Synchronous, broker-neutral contract for a trading platform adapter."""

    def identify(self) -> str: ...
    def capabilities(self) -> PlatformCapabilities: ...
    def is_authenticated(self) -> bool: ...
    def connect(self) -> None: ...
    def disconnect(self) -> None: ...
    def get_account(self) -> AccountSnapshot: ...
    def get_positions(self) -> Sequence[Position]: ...
    def get_orders(self) -> Sequence[Order]: ...
    def get_order(self, order_id: str) -> Order | None: ...
    def place_order(self, request: OrderRequest) -> Order: ...
    def cancel_order(self, order_id: str) -> Order: ...
    def replace_order(self, order_id: str, request: OrderRequest) -> Order: ...
    def get_quote(self, symbol: str) -> Quote: ...


# Backward-compatible name for existing paper-trading integrations.
ExecutionProvider = TradingPlatformAdapter
