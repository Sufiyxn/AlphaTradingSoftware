from datetime import date, datetime
from typing import Any, Protocol


class JournalRepository(Protocol):
    """Storage contract consumed by the platform services."""

    def record_event(self, timestamp: datetime, event_type: str, message: str, *, symbol: str | None = None, context: Any = None) -> None: ...
    def record_error(self, timestamp: datetime, message: str, *, symbol: str | None = None, context: Any = None) -> None: ...
    def record_strategy_signal(self, signal: Any) -> None: ...
    def record_risk_decision(self, decision: Any) -> None: ...
    def record_order(self, order: Any) -> None: ...
    def record_provider_fill(self, fill: Any, *, order_id: str | None = None, client_order_id: str | None = None, symbol: str | None = None, connection_id: str | None = None, provider_instance_id: str | None = None, context: Any = None) -> bool: ...
    def record_trade_open(self, trade: Any, *, setup: Any = None, risk: Any = None, analysis: Any = None) -> None: ...
    def record_trade_close(self, order_id: str, timestamp: datetime, exit_price: float, pnl: float, *, context: Any = None) -> None: ...
    def record_trade_partial(self, order_id: str, timestamp: datetime, price: float, quantity: float, pnl: float, *, context: Any = None) -> None: ...
    def record_trade_risk(self, order_id: str, *, stop_price: float, target_price: float) -> None: ...
    def record_ai_analysis(self, analysis: Any) -> None: ...
    def record_position_event(self, timestamp: datetime, symbol: str, event_type: str, context: Any = None) -> None: ...
    def connection_instance(self, connection_id: str) -> dict[str, Any] | None: ...
    def bind_connection_instance(self, connection_id: str, *, instance_id: str, created_at: datetime) -> dict[str, Any]: ...
    def next_provider_sequence(self, connection_id: str) -> int: ...
    def closed_trades(self, *, start: date | None = None, end: date | None = None, symbol: str | None = None) -> tuple[dict[str, Any], ...]: ...
    def open_trades(self) -> tuple[dict[str, Any], ...]: ...
    def events(self, *, start: date | None = None, end: date | None = None, symbol: str | None = None, limit: int | None = None) -> tuple[dict[str, Any], ...]: ...
    def errors(self, *, start: date | None = None, end: date | None = None, symbol: str | None = None, limit: int | None = None) -> tuple[dict[str, Any], ...]: ...
    def rows(self, kind: str, *, start: date | None = None, end: date | None = None, symbol: str | None = None) -> tuple[dict[str, Any], ...]: ...
    def save_daily_performance(self, day: date, performance: Any) -> None: ...
    def get_daily_performance(self, day: date) -> Any: ...
    def list_daily_performance(self, *, start: date | None = None, end: date | None = None) -> tuple[dict[str, Any], ...]: ...
